#!/usr/bin/env node
/**
 * Renders the policy in security-headers.js into netlify.toml and nginx.conf.
 *
 * Response headers have to be configured separately for every serving layer,
 * and the usual failure mode is that someone tightens one and forgets the
 * others — so the deployed policy quietly differs from the reviewed one. These
 * blocks are generated from a single source instead, and `--check` (run in CI)
 * fails the build if either file has drifted.
 *
 *   node scripts/sync-security-headers.mjs          # rewrite both files
 *   node scripts/sync-security-headers.mjs --check  # verify only, exit 1 on drift
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { SECURITY_HEADERS } from '../security-headers.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BEGIN = '>>> security-headers:begin';
const END = '<<< security-headers:end';

/** TOML escaping: the CSP contains single quotes, which TOML basic strings allow. */
const tomlString = (value) => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const renderNetlify = () => {
    const values = Object.entries(SECURITY_HEADERS)
        .map(([name, value]) => `    ${name} = ${tomlString(value)}`)
        .join('\n');

    return ['[[headers]]', '  for = "/*"', '  [headers.values]', values].join('\n');
};

const renderNginx = () => Object.entries(SECURITY_HEADERS)
    // `always` so the header is still sent on error responses (404, 5xx), which
    // is exactly when a missing frame-ancestors or nosniff matters most.
    .map(([name, value]) => `    add_header ${name} "${value.replace(/"/g, '\\"')}" always;`)
    .join('\n');

const splice = (source, body, commentPrefix) => {
    const begin = source.indexOf(`${commentPrefix}${BEGIN}`);
    const end = source.indexOf(`${commentPrefix}${END}`);
    if (begin === -1 || end === -1) {
        throw new Error(`Missing ${BEGIN} / ${END} markers`);
    }

    const head = source.slice(0, begin + `${commentPrefix}${BEGIN}`.length);
    const tail = source.slice(end);
    return `${head}\n${body}\n${tail}`;
};

const NGINX_SNIPPET_HEADER = [
    '# GENERATED by scripts/sync-security-headers.mjs — do not edit.',
    '# Source of truth: security-headers.js. Regenerate with `npm run headers:sync`.',
    '#',
    "# Included at server level and again inside every location block that sets",
    '# a header of its own, because nginx add_header does not inherit across a',
    '# level that defines its own.',
    '',
].join('\n');

const targets = [
    { file: 'netlify.toml', render: renderNetlify, commentPrefix: '# ' },
    { file: 'nginx-security-headers.conf', whole: () => `${NGINX_SNIPPET_HEADER}${renderNginx().replace(/^ {4}/gm, '')}\n` },
];

const check = process.argv.includes('--check');
let drifted = false;

for (const { file, render, commentPrefix, whole } of targets) {
    const path = join(ROOT, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const next = whole ? whole() : splice(current, render(), commentPrefix);

    if (current === next) {
        console.log(`  ok       ${file}`);
        continue;
    }

    if (check) {
        console.error(`  DRIFTED  ${file}`);
        drifted = true;
    } else {
        writeFileSync(path, next);
        console.log(`  written  ${file}`);
    }
}

if (drifted) {
    console.error('\nsecurity-headers.js and the deploy configs disagree.');
    console.error('Run `npm run headers:sync` and commit the result.');
    process.exit(1);
}
