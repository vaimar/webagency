#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const GENERATED_NOTE = '<!-- Generated by `npm run generate:agent-skills`. Do not edit directly. -->';

const workspacePaths = {
  manifest: path.join(repoRoot, 'agent-skills/manifest.json'),
  claudeDir: path.join(repoRoot, '.claude/skills'),
  promptDir: path.join(repoRoot, '.github/prompts'),
  runtimeDir: path.join(repoRoot, 'agent-skills/runtime'),
};

const manifest = readJson(workspacePaths.manifest);
validateManifest(manifest);

const baseLoad = [manifest.project.primaryGuide, ...manifest.sharedRules];
const skillEntries = manifest.skills.map((skill) => buildSkillEntry(skill, baseLoad));

cleanupGeneratedOutputs(skillEntries);

for (const skill of skillEntries) {
  writeFile(skill.claudeAbsolutePath, renderClaudeWrapper(skill));
  writeFile(skill.copilotAbsolutePath, renderCopilotPrompt(skill));
}

writeFile(
  path.join(workspacePaths.claudeDir, 'skills-index.json'),
  stringifyJson({
    schemaVersion: manifest.schemaVersion,
    sourceManifest: relativePosix(path.join(workspacePaths.claudeDir, 'skills-index.json'), workspacePaths.manifest),
    skills: skillEntries.map((skill) => ({
      id: skill.id,
      path: skill.claudeWrapperPath,
    })),
  }),
);

writeFile(
  path.join(workspacePaths.runtimeDir, 'claude.map.json'),
  stringifyJson({
    runtime: 'claude',
    sourceManifest: relativePosix(path.join(workspacePaths.runtimeDir, 'claude.map.json'), workspacePaths.manifest),
    wrapperIndex: relativePosix(path.join(workspacePaths.runtimeDir, 'claude.map.json'), path.join(workspacePaths.claudeDir, 'skills-index.json')),
    mappings: Object.fromEntries(skillEntries.map((skill) => [skill.id, skill.claudeWrapperPath])),
  }),
);

writeFile(
  path.join(workspacePaths.runtimeDir, 'copilot.map.json'),
  stringifyJson({
    runtime: 'copilot',
    sourceManifest: relativePosix(path.join(workspacePaths.runtimeDir, 'copilot.map.json'), workspacePaths.manifest),
    instructionFile: relativePosix(path.join(workspacePaths.runtimeDir, 'copilot.map.json'), path.join(repoRoot, manifest.project.copilotGuide)),
    promptDirectory: relativePosix(path.join(workspacePaths.runtimeDir, 'copilot.map.json'), workspacePaths.promptDir),
    mappings: Object.fromEntries(skillEntries.map((skill) => [skill.id, skill.copilotPromptPath])),
  }),
);

writeFile(
  path.join(workspacePaths.runtimeDir, 'mcp-skills.json'),
  stringifyJson({
    schemaVersion: manifest.schemaVersion,
    runtime: 'custom-mcp-loader',
    project: manifest.project.id,
    sharedRules: manifest.sharedRules,
    context: manifest.context,
    skills: skillEntries.map((skill) => ({
      id: skill.id,
      title: skill.name,
      prompt: skill.source,
      wrappers: {
        claude: skill.claudeWrapperPath,
        copilot: skill.copilotPromptPath,
      },
    })),
  }),
);

console.log(`Generated ${skillEntries.length} skill wrapper(s) from ${toRepoRelative(workspacePaths.manifest)}.`);

function buildSkillEntry(skill, baseLoadOrder) {
  const wrapper = asRecord(skill.wrapper, `skills[${skill.id}].wrapper`);
  const source = assertString(skill.source, `skills[${skill.id}].source`);
  const slug = path.basename(source, path.extname(source));
  const load = uniquePaths([...baseLoadOrder, ...assertStringArray(wrapper.load, `skills[${skill.id}].wrapper.load`), source]);

  for (const loadPath of load) {
    assertWorkspaceFile(loadPath, `load entry for ${skill.id}`);
  }

  const claudeWrapperPath = `.claude/skills/${slug}/SKILL.md`;
  const copilotPromptPath = `.github/prompts/${slug}.prompt.md`;

  return {
    id: assertString(skill.id, 'skill.id'),
    name: assertString(skill.name, `skills[${skill.id}].name`),
    source,
    slug,
    load,
    claudeUsage: assertString(wrapper.claudeUsage, `skills[${skill.id}].wrapper.claudeUsage`),
    claudePrefer: wrapper.claudePrefer ? assertStringArray(wrapper.claudePrefer, `skills[${skill.id}].wrapper.claudePrefer`) : [],
    copilotGoal: assertString(wrapper.copilotGoal, `skills[${skill.id}].wrapper.copilotGoal`),
    claudeWrapperPath,
    copilotPromptPath,
    claudeAbsolutePath: path.join(repoRoot, claudeWrapperPath),
    copilotAbsolutePath: path.join(repoRoot, copilotPromptPath),
  };
}

function renderClaudeWrapper(skill) {
  const lines = [
    `# ${skill.name}`,
    '',
    GENERATED_NOTE,
    '',
    'Load order:',
    ...skill.load.map((entry, index) => `${index + 1}. \`${entry}\``),
    '',
    `Use this skill ${skill.claudeUsage}`,
  ];

  if (skill.claudePrefer.length > 0) {
    lines.push('', 'Prefer:', ...skill.claudePrefer.map((item) => `- ${item}`));
  }

  lines.push('', '');
  return lines.join('\n');
}

function renderCopilotPrompt(skill) {
  return [
    `# ${skill.name}`,
    '',
    GENERATED_NOTE,
    '',
    `Use \`${skill.id}\`.`,
    '',
    'Load:',
    ...skill.load.map((entry) => `- \`${entry}\``),
    '',
    `Goal: ${skill.copilotGoal}`,
    '',
    '',
  ].join('\n');
}

function cleanupGeneratedOutputs(skillEntries) {
  fs.mkdirSync(workspacePaths.claudeDir, { recursive: true });
  fs.mkdirSync(workspacePaths.promptDir, { recursive: true });
  fs.mkdirSync(workspacePaths.runtimeDir, { recursive: true });

  const expectedClaudeDirs = new Set(skillEntries.map((skill) => skill.slug));
  for (const entry of fs.readdirSync(workspacePaths.claudeDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const skillFile = path.join(workspacePaths.claudeDir, entry.name, 'SKILL.md');
    if (fs.existsSync(skillFile) && !expectedClaudeDirs.has(entry.name)) {
      fs.rmSync(path.join(workspacePaths.claudeDir, entry.name), { recursive: true, force: true });
    }
  }

  const expectedPrompts = new Set(skillEntries.map((skill) => `${skill.slug}.prompt.md`));
  for (const entry of fs.readdirSync(workspacePaths.promptDir, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.prompt.md')) continue;
    if (!expectedPrompts.has(entry.name)) {
      fs.rmSync(path.join(workspacePaths.promptDir, entry.name), { force: true });
    }
  }
}

function validateManifest(currentManifest) {
  if (!currentManifest || typeof currentManifest !== 'object' || Array.isArray(currentManifest)) {
    throw new Error('agent-skills/manifest.json must contain an object root.');
  }

  assertString(currentManifest.project?.id, 'project.id');
  assertString(currentManifest.project?.primaryGuide, 'project.primaryGuide');
  assertString(currentManifest.project?.copilotGuide, 'project.copilotGuide');
  assertStringArray(currentManifest.sharedRules, 'sharedRules');
  assertStringArray(currentManifest.context, 'context');

  const skills = currentManifest.skills;
  if (!Array.isArray(skills) || skills.length === 0) {
    throw new Error('manifest.skills must contain at least one skill.');
  }

  const ids = new Set();
  const slugs = new Set();

  assertWorkspaceFile(currentManifest.project.primaryGuide, 'project.primaryGuide');
  assertWorkspaceFile(currentManifest.project.copilotGuide, 'project.copilotGuide');
  currentManifest.sharedRules.forEach((item) => assertWorkspaceFile(item, 'sharedRules entry'));
  currentManifest.context.forEach((item) => assertWorkspaceFile(item, 'context entry'));

  for (const skill of skills) {
    const id = assertString(skill.id, 'skill.id');
    const source = assertString(skill.source, `skills[${id}].source`);
    const slug = path.basename(source, path.extname(source));

    if (ids.has(id)) {
      throw new Error(`Duplicate skill id detected: ${id}`);
    }
    ids.add(id);

    if (slugs.has(slug)) {
      throw new Error(`Duplicate generated wrapper slug detected: ${slug}`);
    }
    slugs.add(slug);

    assertWorkspaceFile(source, `skills[${id}].source`);
    asRecord(skill.wrapper, `skills[${id}].wrapper`);
  }
}

function assertWorkspaceFile(relativePath, label) {
  const absolutePath = path.join(repoRoot, relativePath);
  if (!fs.existsSync(absolutePath)) {
    throw new Error(`${label} does not exist: ${relativePath}`);
  }
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content.endsWith('\n') ? content : `${content}\n`, 'utf8');
}

function stringifyJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function relativePosix(fromFile, toFile) {
  return path.relative(path.dirname(fromFile), toFile).split(path.sep).join('/');
}

function toRepoRelative(filePath) {
  return path.relative(repoRoot, filePath).split(path.sep).join('/');
}

function uniquePaths(items) {
  const seen = new Set();
  const result = [];

  for (const item of items) {
    if (seen.has(item)) continue;
    seen.add(item);
    result.push(item);
  }

  return result;
}

function asRecord(value, label) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${label} must be an object.`);
  }

  return value;
}

function assertString(value, label) {
  if (typeof value !== 'string' || value.trim().length === 0) {
    throw new Error(`${label} must be a non-empty string.`);
  }

  return value;
}

function assertStringArray(value, label) {
  if (!Array.isArray(value)) {
    throw new Error(`${label} must be an array of strings.`);
  }

  return value.map((item, index) => assertString(item, `${label}[${index}]`));
}

